package agents

import (
	"fmt"
	"path/filepath"
	"strings"
	"unicode/utf8"
)

// Access describes the author's requested grants. MergeAccess only widens them.
type Access struct {
	ExternalDirs  string   `json:"externalDirs,omitempty"`
	Dirs          []string `json:"dirs,omitempty"`
	ExternalWrite bool     `json:"externalWrite,omitempty"`
	Web           bool     `json:"web,omitempty"`
	Scripts       string   `json:"scripts,omitempty"`
	Subagents     bool     `json:"subagents,omitempty"`
	MCP           []string `json:"mcp,omitempty"`
}

type Task struct {
	ID              string   `json:"id"`
	Name            string   `json:"name"`
	Icon            string   `json:"icon"`
	Description     string   `json:"description,omitempty"`
	Prompt          string   `json:"prompt"`
	Agent           string   `json:"agent,omitempty"`
	Scope           string   `json:"scope,omitempty"`
	Place           []string `json:"place"`
	WhenAnnotations string   `json:"whenAnnotations,omitempty"`
	Workdir         string   `json:"workdir,omitempty"`
	Access          Access   `json:"access,omitempty"`
	MaxMinutes      int      `json:"maxMinutes,omitempty"`
}

