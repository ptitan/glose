func RelativeTaskPath(p string) bool {
	// Also reject Windows absolute paths when validating on Unix.
	return p != "" && !filepath.IsAbs(p) && !strings.ContainsAny(p, ":\\") && p != ".." && !strings.HasPrefix(p, "../") && filepath.Clean(p) == p
}

func (a Access) Check(project bool) error {
	if a.ExternalDirs != "" && a.ExternalDirs != "none" && a.ExternalDirs != "list" && a.ExternalDirs != "all" {
		return fmt.Errorf("accès : externalDirs attend none, list ou all")
	}
	if a.Scripts != "" && a.Scripts != "none" && a.Scripts != "python" && a.Scripts != "shell" {
		return fmt.Errorf("accès : scripts attend none, python ou shell")
	}
	if len(a.Dirs) > 0 && a.ExternalDirs != "list" && a.ExternalDirs != "all" {
		return fmt.Errorf("accès : les dossiers exigent externalDirs=list ou all")
	}
	if a.ExternalDirs == "list" && len(a.Dirs) == 0 {
		return fmt.Errorf("accès : liste de dossiers vide")
	}
	if a.ExternalWrite && len(a.Dirs) == 0 {
		return fmt.Errorf("écriture externe : seulement dans les dossiers listés")
	}
	for _, d := range a.Dirs {
		if d == "" || strings.ContainsAny(d, "*?,[]{}!()\n\r") || (project && !RelativeTaskPath(d)) {
			return fmt.Errorf("dossier de consigne invalide : %q", d)
		}
	}
	for _, m := range a.MCP {
		if CheckAlias(m) != nil {
			return fmt.Errorf("nom MCP invalide : %q", m)
		}
	}
	return nil
}

func CheckTasks(tasks []Task, project bool) error {
	seen := map[string]bool{}
	for _, t := range tasks {
		if CheckAlias(t.ID) != nil || seen[t.ID] {
			return fmt.Errorf("identifiant de consigne invalide ou répété : %q", t.ID)
		}
		seen[t.ID] = true
		if strings.TrimSpace(t.Name) == "" || !utf8.ValidString(t.Name) || len(t.Name) > 200 || strings.ContainsAny(t.Name, "\r\n") {
			return fmt.Errorf("%s : nom de consigne invalide", t.ID)
		}
		if strings.TrimSpace(t.Prompt) == "" || !utf8.ValidString(t.Prompt) || len(t.Prompt) > 32000 {
			return fmt.Errorf("%s : texte de consigne vide ou trop long", t.ID)
		}
		known := false
		for _, i := range TaskIcons {
			if i == t.Icon {
				known = true
			}
		}
		if !known {
			return fmt.Errorf("%s : icône Lucide inconnue : %q", t.ID, t.Icon)
		}
		if t.Agent != "" && CheckAlias(t.Agent) != nil {
			return fmt.Errorf("%s : agent invalide", t.ID)
		}
		if t.Scope != "" && t.Scope != "file" && t.Scope != "files" && t.Scope != "project" {
			return fmt.Errorf("%s : portée invalide", t.ID)
		}
		if len(t.Place) == 0 || len(t.Place) > 2 {
			return fmt.Errorf("%s : emplacement manquant ou invalide", t.ID)
		}
		places := map[string]bool{}
		for _, p := range t.Place {
			if (p != "bar" && p != "handover") || places[p] {
				return fmt.Errorf("%s : emplacement invalide", t.ID)
			}
			places[p] = true
		}
		if t.WhenAnnotations != "" && t.WhenAnnotations != "block" && t.WhenAnnotations != "process" {
			return fmt.Errorf("%s : traitement des annotations invalide", t.ID)
		}
		if t.Workdir != "" && project && !RelativeTaskPath(t.Workdir) {
			return fmt.Errorf("%s : workdir doit être relatif au projet", t.ID)
		}
		if t.MaxMinutes < 0 || t.MaxMinutes > 240 {
			return fmt.Errorf("%s : durée de 1 à 240 minutes", t.ID)
		}
		if err := t.Access.Check(project); err != nil {
			return fmt.Errorf("%s : %w", t.ID, err)
		}
	}
	return nil
}

// MergeTasks keeps global order; project entries replace the same stable ID.
func MergeTasks(global, project []Task) []Task {
	out := append([]Task{}, global...)
	for _, t := range project {
		found := false
		for i := range out {
			if out[i].ID == t.ID {
				out[i] = t
				found = true
				break
			}
		}
		if !found {
			out = append(out, t)
		}
	}
	return out
}

func MergeAccess(a, b Access) Access {
	rank := func(s string, values []string) int {
		for i, v := range values {
			if s == v {
				return i
			}
		}
		return 0
	}
	if rank(b.ExternalDirs, []string{"none", "list", "all"}) > rank(a.ExternalDirs, []string{"none", "list", "all"}) {
		a.ExternalDirs = b.ExternalDirs
	}
	if rank(b.Scripts, []string{"none", "python", "shell"}) > rank(a.Scripts, []string{"none", "python", "shell"}) {
		a.Scripts = b.Scripts
	}
	union := func(x, y []string) []string {
		out := append([]string{}, x...)
		for _, v := range y {
			found := false
			for _, w := range out {
				if v == w {
					found = true
				}
			}
			if !found {
				out = append(out, v)
			}
		}
		return out
	}
	a.Dirs = union(a.Dirs, b.Dirs)
	a.MCP = union(a.MCP, b.MCP)
	a.ExternalWrite = a.ExternalWrite || b.ExternalWrite
	a.Web = a.Web || b.Web
	a.Subagents = a.Subagents || b.Subagents
	return a
}
